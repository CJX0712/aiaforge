"""AiaForge closed-loop delivery: push repo to GitHub with three-level degrade.

Levels (autonomous, no human in the loop):
  1. git push  -> primary path (needs git + network)
  2. Git Data API (blobs/tree/commit/ref) -> when git protocol is blocked
  3. Contents API (per-file create/update) -> last resort

Also creates the release tag and a GitHub Release with the benchmark summary.

Author: 晨星 (CJX0712)
"""

from __future__ import annotations

import argparse
import base64
import contextlib
import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

AUTHOR_NAME = "晨星"
AUTHOR_EMAIL = "morningstar@aiaforge.local"
DEFAULT_BRANCH = "main"

# Files that must never be pushed (local-only artifacts).
EXCLUDE = {
    ".pytest_cache",
    ".ruff_cache",
    "__pycache__",
    ".git",
    "benchmark.json",  # regenerated by demo; keep repo clean
}


def run(cmd: list[str], cwd: Path | None = None, check: bool = True) -> str:
    proc = subprocess.run(
        cmd,
        cwd=str(cwd) if cwd else None,
        capture_output=True,
        text=True,
    )
    if check and proc.returncode != 0:
        raise RuntimeError(
            f"cmd failed ({proc.returncode}): {' '.join(cmd)}\n{proc.stderr.strip()}"
        )
    return proc.stdout.strip()


def gh_token() -> str:
    # Prefer explicit env, then ask gh CLI (authenticated session).
    env_tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if env_tok:
        return env_tok
    out = run(["gh", "auth", "token"], check=False)
    if out:
        return out.strip()
    raise RuntimeError("no GitHub token available (set GITHUB_TOKEN or `gh auth login`)")


def api_call(method: str, url: str, token: str, data: dict | None = None) -> dict:
    body = json.dumps(data).encode() if data is not None else None
    req = urllib.request.Request(url, data=body, method=method)
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("X-GitHub-Api-Version", "2022-11-28")
    if body:
        req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            raw = resp.read().decode()
            return json.loads(raw) if raw else {}
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode() if exc.fp else ""
        raise RuntimeError(f"GitHub API {method} {url} -> {exc.code}: {detail}") from exc


def repo_exists(owner: str, name: str, token: str) -> bool:
    try:
        api_call("GET", f"https://api.github.com/repos/{owner}/{name}", token)
        return True
    except RuntimeError:
        return False


def create_repo(owner: str, name: str, token: str, description: str) -> None:
    if repo_exists(owner, name, token):
        print(f"[gh_push] repo {owner}/{name} already exists, skipping create")
        return
    print(f"[gh_push] creating repo {owner}/{name}")
    api_call(
        "POST",
        "https://api.github.com/user/repos",
        token,
        {
            "name": name,
            "description": description,
            "public": True,
            "auto_init": False,
            "license_template": "mit",
        },
    )


def iter_files(local: Path):
    for p in local.rglob("*"):
        if not p.is_file():
            continue
        rel = p.relative_to(local).as_posix()
        if any(rel == e or rel.startswith(e + "/") or e in p.parts for e in EXCLUDE):
            continue
        yield rel, p


# ---- Level 3: Contents API -------------------------------------------------
def push_via_contents(local: Path, owner: str, name: str, token: str) -> None:
    print("[gh_push] L3: Contents API fallback")
    for rel, p in iter_files(local):
        content = p.read_bytes()
        encoded = base64.b64encode(content).decode()
        url = f"https://api.github.com/repos/{owner}/{name}/contents/{rel}"
        # Try update first; if 404, create.
        try:
            existing = api_call("GET", url, token)
            sha = existing.get("sha")
        except RuntimeError:
            sha = None
        payload = {
            "message": f"feat: add {rel} (晨星)",
            "content": encoded,
            "branch": DEFAULT_BRANCH,
            "author": {"name": AUTHOR_NAME, "email": AUTHOR_EMAIL},
        }
        if sha:
            payload["sha"] = sha
        api_call("PUT", url, token, payload)
        print(f"  - put {rel}")


# ---- Level 2: Git Data API -------------------------------------------------
def push_via_gitdata(local: Path, owner: str, name: str, token: str) -> None:
    print("[gh_push] L2: Git Data API fallback")
    base = f"https://api.github.com/repos/{owner}/{name}"
    # Resolve base tree (empty repo -> no branch yet).
    try:
        ref = api_call("GET", f"{base}/git/ref/heads/{DEFAULT_BRANCH}", token)
        base_sha = ref["object"]["sha"]
        base_tree = api_call("GET", f"{base}/git/commits/{base_sha}", token)["tree"]["sha"]
    except RuntimeError:
        base_tree = None  # brand new empty repo

    blobs = {}
    for rel, p in iter_files(local):
        content = p.read_bytes()
        res = api_call(
            "POST",
            f"{base}/git/blobs",
            token,
            {"content": base64.b64encode(content).decode(), "encoding": "base64"},
        )
        blobs[rel] = res["sha"]

    tree = [
        {"path": rel, "mode": "100644", "type": "blob", "sha": sha} for rel, sha in blobs.items()
    ]
    tree_res = api_call("POST", f"{base}/git/trees", token, {"tree": tree})
    tree_sha = tree_res["sha"]

    commit_res = api_call(
        "POST",
        f"{base}/git/commits",
        token,
        {
            "message": "feat: AiaForge initial delivery (晨星)",
            "tree": tree_sha,
            "parents": [base_sha] if base_tree else [],
            "author": {
                "name": AUTHOR_NAME,
                "email": AUTHOR_EMAIL,
                "date": "2026-10-12T00:00:00Z",
            },
        },
    )
    commit_sha = commit_res["sha"]

    if base_tree:
        api_call(
            "PATCH",
            f"{base}/git/refs/heads/{DEFAULT_BRANCH}",
            token,
            {"sha": commit_sha, "force": True},
        )
    else:
        api_call(
            "POST",
            f"{base}/git/refs",
            token,
            {"ref": f"refs/heads/{DEFAULT_BRANCH}", "sha": commit_sha},
        )
    print(f"[gh_push] L2 committed {commit_sha}")


# ---- Level 1: git push -----------------------------------------------------
def push_via_git(local: Path, owner: str, name: str, token: str) -> bool:
    print("[gh_push] L1: git push")
    if not (local / ".git").exists():
        run(["git", "init", "-q"], cwd=local)
        run(["git", "branch", "-M", DEFAULT_BRANCH], cwd=local)
    run(["git", "config", "user.name", AUTHOR_NAME], cwd=local)
    run(["git", "config", "user.email", AUTHOR_EMAIL], cwd=local)
    # Ensure remote points at the freshly created repo.
    remotes = run(["git", "remote", "-v"], cwd=local, check=False)
    remote_url = f"https://{token}@github.com/{owner}/{name}.git"
    if "origin" not in remotes:
        run(["git", "remote", "add", "origin", remote_url], cwd=local)
    else:
        run(["git", "remote", "set-url", "origin", remote_url], cwd=local)

    run(["git", "add", "-A"], cwd=local)
    # Commit only if there is a diff.
    status = run(["git", "status", "--porcelain"], cwd=local, check=False)
    if status.strip():
        run(
            ["git", "commit", "-q", "-m", "feat: AiaForge v0.1.0 delivery (晨星)"],
            cwd=local,
        )
    try:
        run(["git", "push", "-q", "-u", "origin", DEFAULT_BRANCH], cwd=local)
        return True
    except RuntimeError as exc:
        print(f"[gh_push] L1 failed: {exc}")
        return False


def create_release(owner: str, name: str, tag: str, notes: str, token: str) -> None:
    # Local tag (best-effort; ignore if git is unavailable).
    with contextlib.suppress(Exception):
        run(["git", "tag", "-f", tag], cwd=None)
    # Use gh for the release (handles existing-tag/idempotency).
    try:
        run(
            [
                "gh",
                "release",
                "create",
                tag,
                "--repo",
                f"{owner}/{name}",
                "--title",
                f"AiaForge {tag}",
                "--notes",
                notes,
                "--latest",
            ],
            check=False,
        )
        print(f"[gh_push] release {tag} created")
    except Exception as exc:
        print(f"[gh_push] release creation skipped: {exc}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--local", required=True)
    ap.add_argument(
        "--description",
        default="AiaForge: attribute inference attack benchmark (晨星)",
    )
    ap.add_argument("--tag", default="v0.1.0")
    ap.add_argument("--release", default="")
    args = ap.parse_args()

    local = Path(args.local).resolve()
    owner, _, name = args.repo.partition("/")
    if not name:
        name = owner
        owner = "CJX0712"

    token = gh_token()
    create_repo(owner, name, token, args.description)

    pushed = push_via_git(local, owner, name, token)
    if not pushed:
        try:
            push_via_gitdata(local, owner, name, token)
        except RuntimeError as exc:
            print(f"[gh_push] L2 failed: {exc}; trying L3")
            push_via_contents(local, owner, name, token)

    create_release(owner, name, args.tag, args.release, token)
    print(f"[gh_push] DONE https://github.com/{owner}/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
